/** Símbolo para un código: "$" si no se conoce, "" si la moneda no tiene uno propio. */
export function currencySymbol(code: string): string {
  return Object.prototype.hasOwnProperty.call(SYMBOLS, code) ? SYMBOLS[code] : "$";
}
